/** The app mark (same artwork as the app icon), for headers and the login screen. */
export function AppMark({ size = 32, className }: { size?: number; className?: string }) {
  // Unique per instance: a gradient defined inside a hidden (display:none) copy
  // of the mark would otherwise leave every other copy without a background.
  const gradientId = `app-mark-bg-${useId().replace(/[^a-zA-Z0-9_-]/g, '')}`;
  return (
    <svg width={size} height={size} viewBox="0 0 512 512" className={className} aria-hidden>
      <defs>
        <linearGradient id={gradientId} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#2997ff" />
          <stop offset="1" stopColor="#0058c4" />
        </linearGradient>
      </defs>
      <rect width="512" height="512" rx="112" fill={`url(#${gradientId})`} />
      <path d="M150 104h150l70 70v222a24 24 0 0 1-24 24H150a24 24 0 0 1-24-24V128a24 24 0 0 1 24-24z" fill="#fff" />
      <path d="M300 104v46a24 24 0 0 0 24 24h46z" fill="#b9d6fb" />
      <path d="M290 222a62 62 0 1 0 0 92" fill="none" stroke="#0071e3" strokeWidth="26" strokeLinecap="round" />
      <path d="M176 248h84M176 288h84" stroke="#0071e3" strokeWidth="22" strokeLinecap="round" />
      <circle cx="362" cy="380" r="74" fill="#34c759" stroke="#fff" strokeWidth="14" />
      <path d="M328 382l24 24 46-48" fill="none" stroke="#fff" strokeWidth="22" strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}
